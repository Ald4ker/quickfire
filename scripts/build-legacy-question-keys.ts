const ARTIFACT_PATH = path.join(process.cwd(), 'convex', 'seed', 'legacyQuestionKeys.ts');
const SEED_PATH = 'convex/seed/questions.json';

function readSeedAtRef(ref: string): LegacyQuestionKeyRow[] {
  const raw = execFileSync('git', ['show', `${ref}:${SEED_PATH}`], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(raw) as LegacyQuestionKeyRow[];
}

function render(corrections: readonly string[], pairs: readonly (readonly [string, string])[]): string {
  const version = createHash('sha256').update(JSON.stringify(pairs)).digest('hex').slice(0, 12);
  const rows = pairs.map((pair) => `  ${JSON.stringify(pair)},`).join('\n');
  const correctionRows = corrections.map((key) => `  ${JSON.stringify(key)},`).join('\n');

  return `/**
 * GENERATED by scripts/build-legacy-question-keys.ts. Do not edit by hand.
 *
 * Frozen snapshot of the question keys the q<UserID> change replaced:
 *   ${SEED_PATH}@${HISTORICAL_REF} (${pairs.length} position-keyed rows)
 *   -> ${SEED_PATH}@${TRANSITION_REF}
 *
 * It is data, not a projection of current content: it is never rebuilt from a later import,
 * so reordering, renaming or adding questions cannot move an old key onto another question.
 * Every pair was verified against prompt and answer identity when it was built.
 */

export const LEGACY_QUESTION_KEY_SOURCE =
  '${SEED_PATH}@${HISTORICAL_REF} (${pairs.length} rows) -> ${SEED_PATH}@${TRANSITION_REF}';

/** sha256 prefix over LEGACY_QUESTION_KEY_PAIRS; a resumed walk must match it. */
export const LEGACY_QUESTION_KEY_VERSION = '${version}';

/** Position keys only ever existed for the English rows. */
export const LEGACY_SEED_LOCALE = 'en';

/** Legacy keys whose prompt/answer the transition deliberately corrected. */
export const LEGACY_CONTENT_CORRECTIONS: readonly string[] = [
${correctionRows}
];

/** [legacyKey, canonicalKey] in historical seed order. */
export const LEGACY_QUESTION_KEY_PAIRS: readonly (readonly [string, string])[] = [
${rows}
];
`;
}

function main() {
  const historical = readSeedAtRef(HISTORICAL_REF);
  const transition = readSeedAtRef(TRANSITION_REF);
  const composition = composeLegacyQuestionKeyPairs(
    historical,
    transition,
    new Set(CONTENT_CORRECTIONS)
  );

  const problems: string[] = [];
  for (const mismatch of composition.mismatches.slice(0, 20)) {
    problems.push(`  ${mismatch.legacyKey} [${mismatch.reason}] ${mismatch.detail}`);
  }
  if (composition.mismatches.length > 20) {
    problems.push(`  ...and ${composition.mismatches.length - 20} more`);
  }
  for (const stale of composition.correctionsStale) {
    problems.push(`  ${stale} [stale-correction] text matches again; remove it from CONTENT_CORRECTIONS`);
  }
  if (problems.length) {
    throw new Error(
      `refusing to write ${path.relative(process.cwd(), ARTIFACT_PATH)}:\n${problems.join('\n')}`
    );
  }

  const uncorrected = CONTENT_CORRECTIONS.filter(
    (key) => !composition.correctionsApplied.includes(key)
  );
  if (uncorrected.length) {
    throw new Error(
      `CONTENT_CORRECTIONS lists unapplied keys: ${uncorrected.join(', ')}`
    );
  }

  fs.writeFileSync(
    ARTIFACT_PATH,
    render(composition.correctionsApplied, composition.pairs),
    'utf8'
  );

  console.log(
    `Wrote ${composition.pairs.length} pairs to ${ARTIFACT_PATH}\n` +
      `  historical ${HISTORICAL_REF}: ${historical.length} rows\n` +
      `  transition ${TRANSITION_REF}: ${transition.length} rows\n` +
      `  corrections applied: ${composition.correctionsApplied.length}, mismatches: 0`
  );
}

main();
