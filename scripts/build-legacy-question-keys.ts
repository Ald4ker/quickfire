/**
 * Builds convex/seed/legacyQuestionKeys.ts: the frozen `<slug>:<points>:<index>` ->
 * `q<UserID>` snapshot taken at the question key transition.
 *
 * The snapshot contains only keys that existed before the change, read from both ends of the
 * transition at pinned refs (never a moving branch):
 *   1992d4d convex/seed/questions.json  (8,912 position-keyed rows)
 *   6291744 convex/seed/questions.json  (the `q<UserID>` seed this PR ships)
 *
 * Every pair is verified by prompt and answer identity, so a question that moved, was
 * swapped, or was removed aborts the build instead of being written. The rows the
 * transition deliberately corrected are listed in CONTENT_CORRECTIONS below and are
 * re-checked, so a stale entry fails the build instead of quietly widening what is allowed.
 *
 * Run: bunx tsx scripts/build-legacy-question-keys.ts
 * (re-run only when the transition refs or the corrections list change; the output is
 * committed, and nothing at runtime rebuilds it from current source data)
 */

